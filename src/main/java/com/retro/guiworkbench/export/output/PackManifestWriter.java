package com.retro.guiworkbench.export.output;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.retro.guiworkbench.export.model.ExportBlueprint;
import com.retro.guiworkbench.export.model.ExportedTextureData;

import java.io.IOException;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.List;

public final class PackManifestWriter
{
    private static final Gson Json = new GsonBuilder().setPrettyPrinting().create();

    private PackManifestWriter()
    {
    }

    public static void writePackMcmeta(Path target) throws IOException
    {
        String json = """
                {
                  "pack": {
                    "pack_format": 34,
                    "description": "Generated by Retro GUI Workbench"
                  }
                }
                """;
        Files.writeString(target, json, StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING);
    }

    public static void writeTexturesManifest(Path target, List<ExportedTextureData> manifest) throws IOException
    {
        Path parent = target.getParent();
        if (parent != null)
        {
            Files.createDirectories(parent);
        }

        try (Writer writer = Files.newBufferedWriter(target))
        {
            Json.toJson(manifest, writer);
        }
    }

    public static void writeReport(Path target, ExportBlueprint blueprint, int exportedCount) throws IOException
    {
        StringBuilder out = new StringBuilder();
        out.append("Retro GUI Workbench Export\n");
        out.append("Mode: ").append(blueprint.mode()).append('\n');
        out.append("Exported textures: ").append(exportedCount).append('\n');
        out.append("Whitelist: ")
                .append(blueprint.whitelist().isEmpty() ? "<all namespaces>" : blueprint.whitelist())
                .append('\n');
        out.append("Opened namespaces: ")
                .append(blueprint.openedNamespaces().isEmpty() ? "<none logged>" : blueprint.openedNamespaces())
                .append('\n');
        out.append("Editable copies: ").append(blueprint.options().generateEditableCopies()).append('\n');
        out.append("Editable scale: ").append(blueprint.options().editableScale()).append('\n');
        out.append("Guides: ").append(blueprint.options().generateGuides()).append('\n');
        Files.writeString(target, out.toString(), StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING);
    }
}
